# ── the provenance record: everything the journal SI must not carry ────────────────────────────
def build_provenance() -> str:
    rows = []
    for item, record, producer in (
        ("Methods S1", OBJECTIVE_JSON, None),
        ("Methods S2", ENDPOINT_JSON, None),
        ("Note S1", TABLE7_AUDIT, None),
        ("Table S1", OBJECTIVE_JSON, "objective_family"),
        ("Table S1 (curvature)", PANEL_JSON, None),
        ("Table S2", OBJECTIVE_JSON, "objective_family"),
        ("Table S3", ENDPOINT_JSON, None),
        ("Table S4", EXTERNAL_JSON, None),
        ("Table S5", CONVERGENCE_JSON, None),
    ):
        rec = _load(record) if record.suffix == ".json" else {}
        prod = rec.get("producer", "—")
        field = producer or rec.get("producer_field", "")
        rows.append(f"| {item} | `{record.relative_to(REPO)}` | `{prod}` | "
                    f"{'`' + field + '`' if field else '—'} |")

    fig_rows = [f"| Supplementary Figure {n} | `{(FIGURE_SRC / (stem + '.png')).relative_to(REPO)}` "
                f"| `{stem}` |" for n, stem in FIGURES]

    conv = _load(CONVERGENCE_JSON)
    obj = _load(OBJECTIVE_JSON)
    panels = _load(PANEL_JSON)

    return f"""# Paper A — supplementary-material provenance

{STAMP}

**Not part of the submission.** This record holds the repository detail that the fourth review
required be removed from the journal SI (P0-5): which producer emitted each supplementary item,
which archived record it was rendered from, and the record's own internal notes. The SI itself is
`PAPER_A_JFE_SUPPLEMENT.md`; both are generated by `tools/paper_a_supplement.py`, so this table
cannot drift from what was actually rendered.

## Item → record → producer

| supplementary item | archived record | producer | field |
|---|---|---|---|
{chr(10).join(rows)}

## Figures

Rendered images are copied into `docs/submission/figures/` (PNG for the Markdown SI, PDF for
typesetting) by `tools/paper_a_supplement.py --write`. The number → producer assignment is pinned
in `FIGURES` and cross-checked against `docs/figures/PAPER_A_CAPTIONS.md`; a mismatch is a hard
error, so the SI cannot bundle a different image from the one its caption describes.

| supplementary item | rendered source | producer stem |
|---|---|---|
{chr(10).join(fig_rows)}

## Record notes carried by the producers

**Objective family.** {obj['note']}

**Numerical convergence.** Reference cell `{conv['reference_cell']}`; production configuration
`{conv['production_cell']}`; producer `{conv['producer']}`.

**Curvature panels.** `{PANEL_JSON.relative_to(REPO)}` schema version
{panels['schema_version']}, source commit `{panels['source_commit']}`.

## Analyses cited in the audit trail but not in the SI

The dimensional audit `{TABLE7_AUDIT.relative_to(REPO)}` also records the manuscript demotion it
prompted, the guard phrase locking that demotion, and what a future quantitative version of the
constraint would require. Those are repository history and future work; Supplementary Note S1
reproduces only the audit's scientific content.
"""


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else list(argv)
    fresh, prov = build(), build_provenance()
    if "--write" in argv:
        OUT.write_text(fresh, encoding="utf-8")
        PROVENANCE.write_text(prov, encoding="utf-8")
        n = len(bundle_figures())
        print(f"wrote {OUT.relative_to(REPO)}")
        print(f"wrote {PROVENANCE.relative_to(REPO)}")
        print(f"bundled {n} supplementary figure files into {BUNDLE.relative_to(REPO)}")
        return 0
    rc = 0
    for path, text in ((OUT, fresh), (PROVENANCE, prov)):
        if not path.exists():
            print(f"MISSING: {path.relative_to(REPO)} — run with --write")
            rc = 1
        elif path.read_text(encoding="utf-8") != text:
            print(f"STALE: {path.relative_to(REPO)} — run with --write")
            rc = 1
    if gone := missing_figures():
        print(f"MISSING FIGURES in {BUNDLE.relative_to(REPO)}: {', '.join(gone)} — run with --write")
        rc = 1
    if rc == 0:
        print("supplement, provenance record and figure bundle are current")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
