# ── Supplementary Figures S1–S4 ────────────────────────────────────────────────────────────────
def _caption_map() -> dict[str, tuple[str, str]]:
    """{number: (producer stem, caption paragraph)} parsed from the caption document."""
    text = CAPTIONS.read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r"(?m)^### Figure (S\d+) \(`([^`]+)`\)\s*\n+(\*\*Figure S\d+\..*?)(?=\n###|\Z)",
                         text, re.S):
        out[m.group(1)] = (m.group(2), " ".join(m.group(3).split()))
    return out


def _check_figure_map(caps: dict[str, tuple[str, str]]) -> None:
    for number, stem in FIGURES:
        if number not in caps:
            raise SystemExit(f"caption document defines no Figure {number}")
        if caps[number][0] != stem:
            raise SystemExit(
                f"Figure {number} bundles `{stem}` but the caption document assigns it "
                f"`{caps[number][0]}` — the SI would show a different image from the one described")
    extra = sorted(set(caps) - {n for n, _ in FIGURES})
    if extra:
        raise SystemExit(f"caption document defines supplementary figures the SI omits: {extra}")


def figures() -> str:
    caps = _caption_map()
    _check_figure_map(caps)
    parts = []
    for number, stem in FIGURES:
        _, caption = caps[number]
        parts.append(f"""### Supplementary Figure {number}

![Supplementary Figure {number}](figures/{stem}.png)

{caption}""")
    return "\n\n---\n\n".join(parts)


def bundle_figures() -> list[str]:
    """Copy the rendered supplementary figures next to the SI so the bundle is self-contained."""
    BUNDLE.mkdir(parents=True, exist_ok=True)
    written = []
    for _number, stem in FIGURES:
        for ext in ("png", "pdf"):
            src = FIGURE_SRC / f"{stem}.{ext}"
            if not src.exists():
                raise SystemExit(f"supplementary figure not rendered: {src.relative_to(REPO)}")
            shutil.copyfile(src, BUNDLE / src.name)
            written.append(src.name)
    return written


def missing_figures() -> list[str]:
    return [f"{stem}.{ext}" for _n, stem in FIGURES for ext in ("png", "pdf")
            if not (BUNDLE / f"{stem}.{ext}").exists()]


