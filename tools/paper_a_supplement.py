# ── stubs for items whose analysis has not been run ───────────────────────────────────────────
def stub(number: str, title: str, what_to_run: str) -> str:
    return f"""### Supplementary Table {number}

**{title}**

> **NOT YET AVAILABLE.** This item is cited by the main text but the analysis behind it has not
> been run. It is emitted as an explicit stub rather than omitted, so that the dangling reference
> is visible rather than silent.
>
> To fill it: {what_to_run}
"""


def build() -> str:
    parts = [
        "# Supplementary material",
        "",
        STAMP,
        "",
        "**Separating Extractable Content from Extraction Rate in Espresso Models: Limits of "
        "Whole-Cup Measurements and the Value of Time-Resolved Data**",
        "",
        "Every item here is cited by the main text. Tables are generated from the archived "
        "machine-readable result bundles named beneath each one; notes are reproduced from the "
        "archived audit records. Items whose analysis has not been run are marked as such rather "
        "than omitted.",
        "",
        "---",
        "",
        note_s1(), "", "---", "",
        note_s2(), "", "---", "",
        table_s1(), "", "---", "",
        table_s3(), "", "---", "",
        table_s5(), "", "---", "",
        table_s6(),
    ]
    return "\n".join(parts).rstrip() + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else list(argv)
    fresh = build()
    if "--write" in argv:
        OUT.write_text(fresh, encoding="utf-8")
        print(f"wrote {OUT.relative_to(REPO)}")
        return 0
    if not OUT.exists():
        print(f"MISSING: {OUT.relative_to(REPO)} — run with --write")
        return 1
    if OUT.read_text(encoding="utf-8") != fresh:
        print(f"STALE: {OUT.relative_to(REPO)} — run with --write")
        return 1
    print("supplement is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
