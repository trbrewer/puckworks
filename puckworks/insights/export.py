def render_tension_atlas_csv(state) -> str:
    header = ["tension_id", "lens", "lens_letter", "difference_type", "entity_ids",
              "shared_observable", "shared_domain", "difference_summary", "evidence_basis",
              "candidate_discriminator", "data_available", "cheap_test_possible",
              "candidate_id", "human_status", "relation_confidences", "source_paths",
              "source_commit"]
    rows = []
    for t in state["tensions"]:
        rows.append([t.tension_id, t.lens, S.LENSES[t.lens], t.difference_type,
                     " | ".join(t.entity_ids), t.shared_observable, t.shared_domain,
                     t.difference_summary, t.evidence_basis, t.candidate_discriminator,
                     t.data_available, t.cheap_test_possible, t.candidate_id, t.human_status,
                     " | ".join(sorted(set(t.relation_confidences))),
                     " | ".join(sorted({p.source_path for p in t.provenance})),
                     state["corpus"]["commit"]])
    return _csv(header, rows)


def render_tension_atlas_md(state) -> str:
    corpus, tensions = state["corpus"], state["tensions"]
    by_lens = {}
    for t in tensions:
        by_lens.setdefault(t.lens, []).append(t)
    out = [_MD_BANNER, "", "# Tension atlas", "",
           "Commit `%s` · %d rows across %d lenses. A row is a source-bound statement that two "
           "parts of the corpus are comparable and differ in some declared respect. **A row is "
           "not a finding**, and `human_status` stays `UNREVIEWED` until a person rules."
           % (corpus["commit"][:10], len(tensions), len(by_lens)), ""]
    out += ["## Rows per lens", "", "| lens | blueprint §9 | rows |", "|---|---|---|"]
    for lens, rows in sorted(by_lens.items()):
        out.append("| %s | %s | %d |" % (lens, S.LENSES[lens], len(rows)))
    out += ["", "## Lenses not implemented", "",
            "Absent by decision, not oversight — each needs component EXECUTION this layer does "
            "not do:", ""]
    for lens, why in sorted(TA.DEFERRED_LENSES.items()):
        out.append("- **%s** — %s" % (lens, why))
    for lens, rows in sorted(by_lens.items()):
        out += ["", "## %s (%s)" % (lens, S.LENSES[lens]), ""]
        for t in rows:
            out.append("- **%s** [%s] %s" % (t.tension_id, t.difference_type,
                                             t.difference_summary))
            out.append("  - discriminator: %s · data: %s · cheap test: %s · candidate: %s"
                       % (t.candidate_discriminator or "—", t.data_available,
                          t.cheap_test_possible, t.candidate_id or "—"))
            out.append("  - sources: %s"
                       % ", ".join("`%s`" % p for p in sorted({q.source_path
                                                               for q in t.provenance})))
    return "\n".join(out) + "\n"


