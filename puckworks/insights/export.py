def render_snapshot(state) -> str:
    """`INSIGHT_SNAPSHOT.md` — the one file a reader (or a ChatGPT Project) opens first."""
    corpus, tensions, cands = state["corpus"], state["tensions"], state["candidates"]
    counts, summary = corpus["counts"], CD.portfolio_summary(cands)
    by_lens = {}
    for t in tensions:
        by_lens.setdefault(t.lens, []).append(t)

    out = [_MD_BANNER, "", "# Puckworks insight snapshot", "",
           "**Commit** `%s` · **schema** v%d · **generator** v%d"
           % (corpus["commit"], S.SCHEMA_VERSION, CM.GENERATOR_VERSION), "",
           "Every count below is generated from the tree at that commit (blueprint §4.3). "
           "Nothing here is an authority: follow `card_path` / `source_path` to the card, the "
           "manifest row, or the registry entry that owns each statement.", "",
           "## Corpus", "", "| entity kind | count |", "|---|---|"]
    for kind, n in counts["entities_by_kind"].items():
        out.append("| %s | %d |" % (kind, n))
    out += ["", "| relation type | count |", "|---|---|"]
    for rtype, n in counts["relations_by_type"].items():
        out.append("| %s | %d |" % (rtype, n))
    out += ["", "### Registered models by stage", "", "| stage | models |", "|---|---|"]
    for stage, n in counts["models_by_stage"].items():
        out.append("| %s | %d |" % (stage, n))
    out += ["", "### Registered models by evidence strength (registry wording, verbatim)", "",
            "| evidence_strength | models |", "|---|---|"]
    for ev, n in counts["models_by_evidence_strength"].items():
        out.append("| `%s` | %d |" % (ev, n))

    out += ["", "## Tension atlas", "",
            "%d rows across %d lenses." % (len(tensions), len(by_lens)), "",
            "| lens | rows |", "|---|---|"]
    for lens, rows in sorted(by_lens.items()):
        out.append("| %s | %d |" % (lens, len(rows)))
    out += ["", "Not implemented, by decision: %s."
            % ", ".join("**%s** (%s)" % (k, v.split(";")[0])
                        for k, v in sorted(TA.DEFERRED_LENSES.items())), ""]

    out += ["## Candidate portfolio", "",
            "**%d candidates, every one `SEED`.** None scored, ranked, or adjudicated."
            % summary["total"], "", "| lens | candidates |", "|---|---|"]
    for lens, n in summary["by_lens"].items():
        out.append("| %s | %d |" % (lens, n))

    out += ["", "## Existing public claims", "",
            "The repository has already published these; a candidate restating one is a "
            "duplicate:", ""]
    for c in sorted(CM.entities_of(corpus, "claim"), key=lambda e: e["id"]):
        out.append("- **%s** [`%s`] %s" % (c["attrs"].get("claim_id"), c["attrs"].get("badge"),
                                           c["attrs"].get("headline")))

    out += ["", "## Standing negative results", ""]
    for t in sorted(by_lens.get("negative_result", []), key=lambda x: x.tension_id):
        out.append("- %s" % t.difference_summary)

