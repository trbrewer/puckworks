"""Generated artifacts — the corpus map, atlas, portfolio, indices, and the ChatGPT source pack.

Everything under `docs/insights/generated/` is written by this module and MUST NOT be hand-edited:
the tests fail on drift, exactly as the Paper-3 evidence graph's generated matrix does. Curate the
authorities (registry, cards, manifest, claims); regenerate the rest.

**No wall-clock timestamp appears in any tracked artifact.** The blueprint's snapshot manifest
carries `generated_at`, but a timestamp makes every regeneration a diff and makes drift
undetectable, which defeats the staleness control it was meant to serve (§19.7). The commit sha
plus a sha256 per input file identifies a snapshot strictly better — it changes when and only when
the inputs change. `--stamp-time` adds the timestamp for an untracked, human-facing export.
"""
from __future__ import annotations

import csv
import io

from . import candidates as CD, corpus_map as CM, schema as S, tension_atlas as TA

GENERATED_REL = "docs/insights/generated"
PACK_REL = GENERATED_REL + "/chatgpt_project"

BANNER = ("GENERATED by `python -m puckworks.insights write` from the live registry, "
          "docs/cards/, puckworks/data/MANIFEST.csv and docs/public/generated/claims.json. "
          "DO NOT EDIT BY HAND — edits are overwritten and fail the tests. Curate the "
          "authorities instead.")
_MD_BANNER = "<!-- " + BANNER + " -->"


def _csv(header, rows) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    w.writerows(rows)
    return buf.getvalue()


def build_all(commit: str | None = None) -> dict:
    """Build the whole Foundry state once. Returns the pieces every renderer needs."""
    corpus = CM.build(commit)
    tensions = TA.build(corpus)
    cands = CD.generate(corpus, tensions)      # assigns candidate_id back onto the tension rows
    return {"corpus": corpus, "tensions": tensions, "candidates": cands}


