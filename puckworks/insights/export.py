def render_evidence_lineage_index(state) -> str:
    """Per-dataset lineage: the manifest's own wording, the derived tags, and the consumers."""
    corpus = state["corpus"]
    consumers = {}
    for r in CM.relations_of(corpus, "CALIBRATED_FROM"):
        consumers.setdefault(r["target"], []).append(r["source"].split(":", 1)[-1])
    claims = {}
    for r in CM.relations_of(corpus, "SUPPORTS_CLAIM"):
        claims.setdefault(r["source"], []).append(r["target"].split(":", 1)[-1])

    header = ["dataset_id", "source_card_as_written", "source_card_resolved",
              "validation_strength_verbatim", "derived_lineage_tags", "uncertainty_retained",
              "extraction_method", "same_source_consumers", "claims_using_it", "caveat_verbatim"]
    rows = []
    for d in sorted(CM.entities_of(corpus, "dataset"), key=lambda e: e["id"]):
        a = d["attrs"]
        rows.append([d["label"], a.get("source_card", ""), a.get("source_card_resolved", ""),
                     a.get("validation_strength", ""), " | ".join(a.get("lineage_tags", [])),
                     a.get("uncertainty_retained", ""), a.get("extraction_method", ""),
                     " | ".join(sorted(set(consumers.get(d["id"], [])))),
                     " | ".join(sorted(set(claims.get(d["id"], [])))), a.get("caveat", "")])
    return _csv(header, rows)


def render_closure_index(state) -> str:
    """Per-calibration-component closure index (blueprint §15.3)."""
    corpus = state["corpus"]
    cand_by_entity = {}
    for c in state["candidates"]:
        for e in c.entity_ids:
            cand_by_entity.setdefault(e, []).append(c.id)

    header = ["closure_component", "stage", "provenance_class", "evidence_strength_verbatim",
              "declared_validity_range_verbatim", "gates", "runtime_consumers_same_stage",
              "candidate_ids"]
    runtime_by_stage = {}
    for m in CM.entities_of(corpus, "model"):
        if m["attrs"].get("execution_role") == "runtime":
            runtime_by_stage.setdefault(m["attrs"].get("stage"), []).append(m["label"])
    rows = []
    for m in sorted(CM.entities_of(corpus, "model"), key=lambda e: e["id"]):
        a = m["attrs"]
        if a.get("execution_role") != "calibration":
            continue
        rows.append([m["label"], a.get("stage", ""), a.get("provenance_class", ""),
                     a.get("evidence_strength", ""), a.get("valid_range", ""),
                     " | ".join(a.get("gates", [])),
                     " | ".join(sorted(runtime_by_stage.get(a.get("stage"), []))),
                     " | ".join(sorted(set(cand_by_entity.get(m["id"], []))))])
    return _csv(header, rows)


