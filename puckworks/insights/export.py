def generate_all(state=None, commit: str | None = None) -> dict:
    """`{relative path: content}` for every tracked artifact. Pure — writes nothing."""
    state = state or build_all(commit)
    return {rel: render(state) for rel, render in ARTIFACTS}


def snapshot_manifest(contents: dict, state, stamp_time: bool = False) -> dict:
    """Build integrity record (blueprint §8.6): commit, input hashes, output hashes."""
    man = {
        "repository": "trbrewer/puckworks",
        "commit": state["corpus"]["commit"],
        "schema_version": S.SCHEMA_VERSION,
        "generator_version": CM.GENERATOR_VERSION,
        "counts": {"entities": state["corpus"]["counts"]["entities_total"],
                   "relations": state["corpus"]["counts"]["relations_total"],
                   "tensions": len(state["tensions"]),
                   "candidates": len(state["candidates"]),
                   "warnings": len(state["corpus"]["warnings"])},
        "inputs": state["corpus"]["inputs"],
        "outputs": [{"path": rel, "sha256": S.sha256_text(text)}
                    for rel, text in sorted(contents.items())],
        "pack": [name for name, _ in PACK],
    }
    if stamp_time:
        # untracked, human-facing exports only — see the module docstring
        import datetime
        man["generated_at"] = datetime.datetime.now(datetime.timezone.utc).isoformat()
    return man


def write(commit: str | None = None, stamp_time: bool = False) -> list:
    """Write every tracked artifact, the snapshot manifest, and the ChatGPT pack. Returns paths."""
    state = build_all(commit)
    contents = generate_all(state)
    written = []
    for rel, text in sorted(contents.items()):
        p = S.REPO_ROOT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        written.append(rel)

    man_rel = GENERATED_REL + "/snapshot_manifest.json"
    man_path = S.REPO_ROOT / man_rel
    man_path.write_text(S.canonical_json(snapshot_manifest(contents, state, stamp_time)),
                        encoding="utf-8")
    written.append(man_rel)

    pack_dir = S.REPO_ROOT / PACK_REL
    pack_dir.mkdir(parents=True, exist_ok=True)
    for name, src_rel in PACK:
        src = S.REPO_ROOT / src_rel
        if not src.exists():
            continue
        (pack_dir / name).write_text(src.read_text(encoding="utf-8"), encoding="utf-8")
        written.append(PACK_REL + "/" + name)
    return written


def verify() -> list:
    """Check the tracked artifacts against the tree. Returns problems, most urgent first.

    Two signals, deliberately distinguished — a naive "regenerate and diff" check would conflate
    them and, worse, would fail on every commit, because the artifacts record the commit they were
    generated from and HEAD moves the moment they are committed:

      * **STALE** — an input file's sha256 differs from the one recorded in the snapshot manifest.
        The authorities moved; regenerate. Content comparison is meaningless until you do, so
        staleness short-circuits.
      * **DRIFT** — inputs are unchanged, but a tracked artifact's bytes differ from what the
        generator produces at the SAME commit. That means someone hand-edited a generated file.

    Regenerating at the manifest's stored commit is what makes DRIFT mean "hand-edited" rather
    than "committed since".
    """
    import json
    man_path = S.REPO_ROOT / (GENERATED_REL + "/snapshot_manifest.json")
    if not man_path.exists():
        return ["MISSING: %s/snapshot_manifest.json (run `python -m puckworks.insights write`)"
                % GENERATED_REL]
    stored = json.loads(man_path.read_text(encoding="utf-8"))

    current = {d["path"]: d["sha256"] for d in CM._input_hashes()}
    recorded = {d["path"]: d["sha256"] for d in stored.get("inputs", [])}
    problems = []
    for path in sorted(set(recorded) | set(current)):
        if path not in current:
            problems.append("STALE: input %s has been removed since the snapshot" % path)
        elif path not in recorded:
            problems.append("STALE: input %s is new since the snapshot" % path)
        elif recorded[path] != current[path]:
            problems.append("STALE: input %s changed since the snapshot" % path)
    if problems:
        return problems + ["-> run `python -m puckworks.insights write` to regenerate"]

    contents = generate_all(commit=stored.get("commit", ""))
    for rel, text in sorted(contents.items()):
        p = S.REPO_ROOT / rel
        if not p.exists():
            problems.append("MISSING: %s (run `python -m puckworks.insights write`)" % rel)
        elif p.read_text(encoding="utf-8") != text:
            problems.append("DRIFT: %s was hand-edited — regenerate instead" % rel)
    # The pack is a gitignored re-export, so its ABSENCE is normal (a fresh clone has never run
    # `write`). Only a pack that exists and disagrees with its source is a problem.
    for name, src_rel in PACK:
        pack_file = S.REPO_ROOT / PACK_REL / name
        src = S.REPO_ROOT / src_rel
        if not (pack_file.exists() and src.exists()):
            continue
        if pack_file.read_text(encoding="utf-8") != src.read_text(encoding="utf-8"):
            problems.append("PACK_DRIFT: %s/%s differs from %s — re-run `write`"
                            % (PACK_REL, name, src_rel))
    return problems
