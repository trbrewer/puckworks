    fig, axes = plt.subplots(2, 2, figsize=(12.5, 9.6))

    # --- A: labelled fixture geometry — an x-z slice through EACH lane, stacked, so the
    #        mirrored segment order and the bridge are both visible in one panel.
    ax = axes[0, 0]
    S = S_COARSE
    ap = doc["aperture_freeze"]["selected"][len(doc["aperture_freeze"]["selected"]) // 2]
    mask, meta = build_fixture(S, aperture=ap, variant="mirror")
    y1 = (BASE["lane1_lo"] + BASE["lane1_hi"]) // 2 * S
    y2 = (BASE["lane2_lo"] + BASE["lane2_hi"]) // 2 * S
    sep = np.full((2, mask.shape[0]), 0.45)
    img = np.concatenate([mask[:, y2, :].T.astype(float), sep,
                          mask[:, y1, :].T.astype(float)], axis=0)
    ax.imshow(img, origin="lower", cmap="Greys", aspect="auto", interpolation="nearest",
              vmin=0, vmax=1)
    nz = mask.shape[2]
    for x, col, ls, lab in ((meta["x_node_in"], "tab:blue", "-", "node"),
                            (meta["x_node_out"], "tab:blue", "-", None),
                            (meta["x_meas_a"], "tab:red", "--", "flux plane a"),
                            (meta["x_meas_b"], "tab:red", ":", "flux plane b")):
        ax.axvline(x, color=col, lw=1.1, ls=ls, label=lab)
    axc = (meta["aperture_x"][0] + meta["aperture_x"][1]) / 2.0
    ax.annotate("bridge", xy=(axc, nz + 1), xytext=(axc, nz + 7), fontsize=8, color="tab:orange",
                ha="center", arrowprops=dict(arrowstyle="->", color="tab:orange", lw=1.2))
    ax.axhline(nz + 1, color="0.6", lw=0.8)
    ax.set_yticks([nz / 2, nz + 2 + nz / 2])
    ax.set_yticklabels(["lane 2\n(low→high)", "lane 1\n(high→low)"], fontsize=8)
    ax.set_title("A  virtual fixture: x–z slice through each lane (solid black)\n"
                 "S=%d, aperture kx=%d kz=%d · blue = node surfaces · red = outlet-flux planes"
                 % (S, ap["kx"], ap["kz"]), fontsize=9)
    ax.set_xlabel("x (lattice) — flow →")
    ax.legend(fontsize=7, loc="lower right", framealpha=0.9)

    # --- B: Xi_hat vs Xi_field, log-log, 1:1 and factor-of-two bounds ---
    ax = axes[0, 1]
    lo, hi = 1e-3, 1e2
    xs = np.array([lo, hi])
    ax.plot(xs, xs, "k-", lw=1, label="1:1")
    ax.plot(xs, 2 * xs, "k--", lw=0.8, label="factor 2")
    ax.plot(xs, 0.5 * xs, "k--", lw=0.8)
    ax.axvspan(XI_WINDOW_LO, XI_WINDOW_HI, color="tab:orange", alpha=0.12,
               label="WP6 1% window")
    for S, mk in ((S_COARSE, "o"), (S_FINE, "s")):
        pts = [(r["truth"]["Xi_field"], r["inference"]["Xi_hat"]) for r in doc["cases"]
               if r["role"] == "primary" and r["S"] == S and r["inference"]["Xi_hat"]]
        if pts:
            ax.plot(*zip(*pts), mk, ms=6, label="S=%d" % S)
    sw = [(r["Xi_field_swap"], r["Xi_hat_swap"]) for r in doc["path_swap"]
          if r.get("Xi_hat_swap") and r.get("Xi_field_swap")]
    if sw:
        ax.plot(*zip(*sw), "^", ms=6, mfc="none", label="path-swapped")
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlabel(r"$\Xi_{\rm field}$ (independent, in-situ)")
    ax.set_ylabel(r"$\hat\Xi$ (boundary inverse)")
    ax.set_title("B  cross-model recovery", fontsize=9)
    ax.legend(fontsize=7, loc="upper left")
    ax.grid(alpha=0.25, which="both")

    # --- C: boundary signatures ---
    ax = axes[1, 0]
    for S, mk in ((S_COARSE, "o"), (S_FINE, "s")):
        d = [(r["truth"]["Xi_field"], r["boundary"]["R"] - 1.0, r["boundary"]["s"] - 0.5)
             for r in doc["cases"] if r["role"] == "primary" and r["S"] == S]
        if d:
            x, r_, s_ = zip(*d)
            ax.plot(x, r_, mk, color="tab:blue", ms=5, label="R-1 (S=%d)" % S)
            ax.plot(x, s_, mk, color="tab:red", ms=5, mfc="none", label="s-1/2 (S=%d)" % S)
    d = [(r["Xi_field_swap"], r["R_swap"] - 1.0, r["s_swap"] - 0.5) for r in doc["path_swap"]
         if r.get("Xi_field_swap")]
    if d:
        x, r_, s_ = zip(*d)
        ax.plot(x, s_, "^", color="tab:red", ms=6, label="s-1/2 (swapped)")
    ax.axhline(0, color="k", lw=0.6)
    ax.set_xscale("log")
    ax.set_xlim(1e-2, 1e2)
    ax.set_xlabel(r"$\Xi_{\rm field}$"); ax.set_ylabel("boundary signature")
    ax.set_title("C  boundary signatures and path-swap sign reversal", fontsize=9)
    ax.legend(fontsize=7); ax.grid(alpha=0.25)

    # --- D: reduction diagnostics ---
    ax = axes[1, 1]
    d = [(r["truth"]["Xi_field"], r["truth"].get("Xi_coupon")) for r in doc["cases"]
         if r["role"] == "primary" and r["truth"].get("Xi_coupon")]
    if d:
        ax.plot(*zip(*d), "d", color="tab:purple", ms=6, label=r"$\Xi_{\rm coupon}$")
    ax.plot(xs, xs, "k-", lw=1)
    nu = [(r["truth"]["Xi_field"], r["truth"]["nonuniformity"]["node_in_sd_over_dP"])
          for r in doc["cases"] if r["role"] == "primary"]
    if nu:
        ax2 = ax.twinx()
        ax2.plot(*zip(*nu), "x", color="tab:gray", ms=5)
        ax2.set_ylabel("node pressure SD / ΔP", color="tab:gray", fontsize=8)
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlim(lo, hi); ax.set_ylim(lo, hi)
    ax.set_xlabel(r"$\Xi_{\rm field}$"); ax.set_ylabel(r"$\Xi_{\rm coupon}$")
    ax.set_title("D  subcomponent composability and node nonuniformity", fontsize=9)
    ax.legend(fontsize=7); ax.grid(alpha=0.25, which="both")

    invalid = doc["disposition"] == "INVALID_EXECUTION"
    fig.suptitle("RP-D-LC-001 — deterministic 3D lateral-coupling virtual fixture · "
                 "CROSS-MODEL NUMERICAL VERIFICATION ONLY · not experimental validation · "
                 "disposition: %s" % doc["disposition"], fontsize=9)
    if invalid:
        # Every recovery number on this figure is diagnostic only. Say so ON the figure, not in a
        # caption a reader can separate from it.
        fig.text(0.5, 0.5, "DIAGNOSTIC ONLY\nINVALID EXECUTION\ncross-model transfer NOT adjudicated",
                 fontsize=34, color="tab:red", alpha=0.16, ha="center", va="center",
                 rotation=24, zorder=10, fontweight="bold")
        fig.text(0.5, 0.945,
                 "EXECUTION VALIDITY FAILED — these panels are DIAGNOSTIC ONLY and may not be "
                 "quoted as recovery, mechanism-only transfer, or a weak quantitative success. "
                 "The cross-model transfer question is UNADJUDICATED, not negative.",
                 fontsize=8, color="tab:red", ha="center", va="top", wrap=True)
    fig.tight_layout(rect=(0, 0, 1, 0.93 if invalid else 0.96))
    fig.savefig(path, dpi=140)
    plt.close(fig)
    return path


