# 4. FIELD READERS — the TRUTH pipeline. NEVER calls the WP6 inverse.
# ==========================================================================================

def plane_flux(ux, mask, x, y_slice=None):
    """Axial volumetric flux through the lattice plane at index ``x`` (lattice units).
    ``ux`` must be the solver's returned ux (which already carries the +g/2 correction);
    solid nodes are masked here because the kernel returns g/2 there, not 0."""
    u = np.where(mask[x], 0.0, ux[x])
    if y_slice is not None:
        u = u[y_slice[0]:y_slice[1]]
    return float(u.sum())


def plane_pressure(rho, mask, x, g, y_slice=None):
    """Fluid-area-averaged PHYSICAL pressure on the lattice plane at ``x``.

    In the periodic body-force formulation the lattice density carries only the periodic part of
    the pressure; the physical field is  p = rho/3 - g*x  (see BOUNDARY_TOPOLOGY_ADJUDICATION.md
    §2). Returns (mean, std, n_fluid) so pressure NONUNIFORMITY over a nominal node surface is
    always reported alongside the mean, never hidden inside it."""
    fl = ~mask[x]
    if y_slice is not None:
        fl = fl.copy()
        fl[:y_slice[0]] = False
        fl[y_slice[1]:] = False
    vals = rho[x][fl] / 3.0 - g * x
    return float(vals.mean()), float(vals.std()), int(fl.sum())


def boundary_record_from_fields(res_open, res_blocked, mask_open, mask_blocked, meta, g):
    """Form the SIX boundary numbers (and only those) from the two solver results.

    Everything read here is available at the boundary of a physical fixture: the two node-plane
    pressures, the total flow, and the two separately measured lane outlet fluxes. No internal
    pressure, no bridge flux, no calibrated conductance, no prescribed aperture size."""
    out = {}
    for tag, res, mask in (("open", res_open, mask_open), ("blocked", res_blocked, mask_blocked)):
        ux, rho = res["ux"], res["rho"]
        xin, xout = meta["x_node_in"], meta["x_node_out"]
        p_in, p_in_sd, n_in = plane_pressure(rho, mask, xin, g)
        p_out, p_out_sd, n_out = plane_pressure(rho, mask, xout, g)
        q1 = plane_flux(ux, mask, meta["x_meas_a"], meta["lane1_y"])
        q2 = plane_flux(ux, mask, meta["x_meas_a"], meta["lane2_y"])
        q1b = plane_flux(ux, mask, meta["x_meas_b"], meta["lane1_y"])
        q2b = plane_flux(ux, mask, meta["x_meas_b"], meta["lane2_y"])
        out[tag] = {"dP": p_in - p_out, "Q": q1 + q2, "q1": q1, "q2": q2,
                    "q1_plane_b": q1b, "q2_plane_b": q2b,
                    "p_node_in": p_in, "p_node_out": p_out,
                    "p_node_in_sd": p_in_sd, "p_node_out_sd": p_out_sd,
                    "n_node_in": n_in, "n_node_out": n_out,
                    "steps": int(res["steps"]), "converged": bool(res["steps"] < MAX_STEPS)}
    return out


def field_truth(res_open, res_blocked, mask_open, mask_blocked, meta, g):
    """The INDEPENDENT in-situ coarse-grained truth (PROTOCOL §8.2). Reads internal pressure and
    velocity fields and the prescribed geometry only. It NEVER calls the WP6 inverse, and its
    output is joined to the inference record only after inference has been recorded."""
    if meta["aperture_x"] is None:
        raise ValueError("field_truth needs the OPEN fixture's aperture footprint")
    ax, az = meta["aperture_x"], meta["aperture_z"]
    xin, xout = meta["x_node_in"], meta["x_node_out"]

    def node_pressures(res, mask):
        rho = res["rho"]
        pin = plane_pressure(rho, mask, xin, g)
        pout = plane_pressure(rho, mask, xout, g)
        return pin, pout

    def face_pressure(res, mask, y):
        """Area-averaged physical pressure on the aperture footprint at lattice row ``y``."""
        rho, vals = res["rho"], []
        for x in range(ax[0], ax[1]):
            fl = ~mask[x, y, az[0]:az[1]]
            if fl.any():
                vals.append(rho[x, y, az[0]:az[1]][fl] / 3.0 - g * x)
        if not vals:
            return float("nan"), float("nan"), 0
        v = np.concatenate(vals)
        return float(v.mean()), float(v.std()), int(v.size)

    # ---- blocked fixture: the four axial segment conductances, coarse-grained in situ --------
    (pin_b, pin_b_sd, _), (pout_b, pout_b_sd, _) = node_pressures(res_blocked, mask_blocked)
    q1_0 = plane_flux(res_blocked["ux"], mask_blocked, meta["x_meas_a"], meta["lane1_y"])
    q2_0 = plane_flux(res_blocked["ux"], mask_blocked, meta["x_meas_a"], meta["lane2_y"])
    p1_0, p1_0_sd, p1_0_n = face_pressure(res_blocked, mask_blocked, meta["y_face1"])
    p2_0, p2_0_sd, p2_0_n = face_pressure(res_blocked, mask_blocked, meta["y_face2"])
    g1_top = q1_0 / (pin_b - p1_0)
    g1_bot = q1_0 / (p1_0 - pout_b)
    g2_top = q2_0 / (pin_b - p2_0)
    g2_bot = q2_0 / (p2_0 - pout_b)
    A1, A2 = g1_top + g1_bot, g2_top + g2_bot
    c_field = (g1_top - g1_bot) / A1
    c_field_lane2 = (g2_bot - g2_top) / A2
    X = g1_top * g2_bot - g2_top * g1_bot

    # ---- open fixture: the signed lateral flux and the local pressure gap that drives it -----
    uy = res_open["uy"]
    yb = meta["y_bridge"]
    q_lat = float(np.where(mask_open[:, yb, :], 0.0, uy[:, yb, :])[ax[0]:ax[1], az[0]:az[1]].sum())
    yb2 = yb - 1
    q_lat_alt = float(
        np.where(mask_open[:, yb2, :], 0.0, uy[:, yb2, :])[ax[0]:ax[1], az[0]:az[1]].sum())
    p1, p1_sd, p1_n = face_pressure(res_open, mask_open, meta["y_face1"])
    p2, p2_sd, p2_n = face_pressure(res_open, mask_open, meta["y_face2"])
    gap = p1 - p2
    ok = bool(np.isfinite(gap) and gap != 0.0 and np.sign(gap) == np.sign(q_lat) and q_lat != 0.0)
    G_lat = (q_lat / gap) if ok else float("nan")
    Xi_field = G_lat * (1.0 / A1 + 1.0 / A2) if ok else float("nan")

    return {
        "g1_top": g1_top, "g1_bot": g1_bot, "g2_top": g2_top, "g2_bot": g2_bot,
        "A1_field": A1, "A2_field": A2, "c_field": c_field, "c_field_lane2": c_field_lane2,
        "c_field_lane_asymmetry": c_field - c_field_lane2,
        "X_cross_product": X, "X_normalised": X / (A1 * A2),
        "q1_blocked": q1_0, "q2_blocked": q2_0,
        "blocked_share": q1_0 / (q1_0 + q2_0),
        "p_mid1_blocked": p1_0, "p_mid2_blocked": p2_0,
        "p_mid_gap_blocked": p1_0 - p2_0,
        "q_lat": q_lat, "q_lat_alt_plane": q_lat_alt,
        "q_lat_plane_rel_diff": (abs(q_lat_alt - q_lat) / abs(q_lat)) if q_lat else float("nan"),
        "p_face1_open": p1, "p_face2_open": p2, "p_face_gap_open": gap,
        "G_lat_field": G_lat, "Xi_field": Xi_field,
        "gap_sign_consistent": ok,
        "nonuniformity": {
            "node_in_sd_over_dP": pin_b_sd / (pin_b - pout_b),
            "node_out_sd_over_dP": pout_b_sd / (pin_b - pout_b),
            "face1_sd_over_gap": (p1_sd / abs(gap)) if ok else float("nan"),
            "face2_sd_over_gap": (p2_sd / abs(gap)) if ok else float("nan"),
            "face1_sd_blocked_over_gap": (p1_0_sd / abs(p1_0 - p2_0)) if p1_0 != p2_0 else float("nan"),
            "n_face1": p1_n, "n_face2": p2_n, "n_face1_blocked": p1_0_n, "n_face2_blocked": p2_0_n,
        },
    }


def coupon_truth(a_coupon, b_coupon, g_bridge_coupon):
    """The SEPARATE composability prediction (PROTOCOL §8.1): what the two-node network says the
    assembled mirror fixture should be, using only independently calibrated pieces."""
    c = (a_coupon - b_coupon) / (a_coupon + b_coupon)
    A1 = A2 = a_coupon + b_coupon
    return {"a_coupon": a_coupon, "b_coupon": b_coupon, "c_coupon": c,
            "A1_coupon": A1, "A2_coupon": A2, "G_bridge_coupon": g_bridge_coupon,
            "Xi_coupon": g_bridge_coupon * (1.0 / A1 + 1.0 / A2)}


