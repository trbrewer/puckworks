    ap.add_argument("--write", action="store_true")
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--figure", action="store_true")
    a = ap.parse_args(argv)
    if a.write:
        write()
        return 0
    if a.verify:
        return verify()
    if a.figure:
        print(figure())
        return 0
    ap.print_help()
    return 0


