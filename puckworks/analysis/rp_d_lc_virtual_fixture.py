def _sha(rel):
    p = REPO_ROOT / rel
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None


def _round(o, nd=_RECORD_DP):
    if isinstance(o, float):
        if math.isnan(o):
            return None
        if math.isinf(o):
            return "inf" if o > 0 else "-inf"
        return round(o, nd)
    if isinstance(o, dict):
        return {k: _round(v, nd) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_round(v, nd) for v in o]
    return o


def load_runs():
    """Load the committed compact run record produced by the slow driver."""
    p = REPO_ROOT / RUNS_REL / "run_record.json"
    if not p.exists():
        raise FileNotFoundError(
            "no run record at %s — execute the heavy driver first:\n"
            "  python -m puckworks.validation.slow.rp_d_lc_001 --backend reference "
            "--mode primary --output <gitignored-run-dir>" % p)
    return json.loads(p.read_text())


