def _base_is_plenum(x: int) -> bool:
    return min(x, BASE["nx"] - x) < BASE["plenum_half"]


def _base_lane_height(x: int, lane: int) -> int:
    """Slot height (base voxels, counted up from z_lo) of `lane` at base station `x`."""
    if BASE["seg_top_lo"] <= x <= BASE["seg_top_hi"]:
        return BASE["h_high"] if lane == 1 else BASE["h_low"]
    if BASE["seg_bot_lo"] <= x <= BASE["seg_bot_hi"]:
        return BASE["h_low"] if lane == 1 else BASE["h_high"]
    return BASE["h_low"]                      # the transition band: both lanes low


def _base_aperture_x(kx: int):
    if kx % 2 != 1:
        raise ValueError("aperture kx must be odd so it is centred on the mirror plane, got %r" % kx)
    half = (kx - 1) // 2
    lo, hi = BASE["bridge_centre"] - half, BASE["bridge_centre"] + half
    if lo < BASE["trans_lo"] or hi > BASE["trans_hi"]:
        raise ValueError("aperture kx=%r does not fit the transition band" % kx)
    return lo, hi


def base_mask(aperture=None, variant="mirror"):
    """The frozen base template as a boolean SOLID mask of shape (nx, ny, nz).

    ``aperture`` None -> the blocked fixture (the divider is continuous). A dict ``{kx, kz}``
    opens the lateral bridge and changes NOTHING else. ``variant`` is 'mirror' (lane 2 carries
    the reversed segment order) or 'identical' (both lanes ordered like lane 1 — the negative
    control, which is structurally degenerate: X = g1t*g2b - g2t*g1b = 0).
    """
    if variant not in ("mirror", "identical"):
        raise ValueError("variant must be 'mirror' or 'identical', got %r" % (variant,))
    nx, ny, nz = BASE["nx"], BASE["ny"], BASE["nz"]
    solid = np.ones((nx, ny, nz), dtype=bool)
    z_lo, z_hi_full = BASE["z_lo"], BASE["z_lo"] + BASE["h_high"] - 1
    for x in range(nx):
        if _base_is_plenum(x):
            solid[x, 1:ny - 1, z_lo:z_hi_full + 1] = False       # one common, full-section node
            continue
        for lane, (ylo, yhi) in ((1, (BASE["lane1_lo"], BASE["lane1_hi"])),
                                 (2, (BASE["lane2_lo"], BASE["lane2_hi"]))):
            h = _base_lane_height(x, 1 if variant == "identical" else lane)
            solid[x, ylo:yhi + 1, z_lo:z_lo + h] = False
    if aperture is not None:
        ax_lo, ax_hi = _base_aperture_x(int(aperture["kx"]))
        kz = int(aperture["kz"])
        if not 1 <= kz <= BASE["h_low"]:
            raise ValueError("aperture kz must lie in 1..%d, got %r" % (BASE["h_low"], kz))
        solid[ax_lo:ax_hi + 1, BASE["div_lo"]:BASE["div_hi"] + 1, z_lo:z_lo + kz] = False
    return solid


def scale(mask_b, S: int):
    """Replicate a base mask S times on every axis — exact geometric similarity."""
    if not isinstance(S, int) or isinstance(S, bool) or S < 1:
        raise ValueError("S must be a positive int, got %r" % (S,))
    return np.repeat(np.repeat(np.repeat(mask_b, S, axis=0), S, axis=1), S, axis=2)


def mirror_x(mask, S: int):
    """The exact voxel-index x-reflection about the fixture's mirror planes (x = 0 and
    x = bridge_centre). Cellwise: base b -> (nx - b) mod nx, with sub-cell order reversed."""
    return np.roll(np.flip(mask, axis=0), S, axis=0)


def swap_paths(mask):
    """The exact path-swap: reflect y about the divider mid-plane, exchanging lane 1 and lane 2.
    This is an index transformation of the SAME array — the swapped fixture is never rebuilt."""
    return np.flip(mask, axis=1)


def _apply_perturbation(mask, S: int, name: str):
    """Apply a predeclared one-voxel adversarial perturbation (Arm I). Returns a NEW mask."""
    spec = PERTURBATIONS[name]
    out = mask.copy()
    if spec["kind"] == "plug":
        bx, by, bz = spec["base"]
        out[bx * S, by * S, bz * S] = True                     # exactly one lattice voxel
    elif spec["kind"] == "slab":
        # move lane 1's upstream-segment end plane by one lattice voxel: the LAST lattice plane
        # of base cell `base_x` reverts from the high slot to the low slot, in lane 1 only.
        x = (spec["base_x"] + 1) * S - 1
        ylo, yhi = BASE["lane1_lo"] * S, (BASE["lane1_hi"] + 1) * S - 1
        zlo = (BASE["z_lo"] + BASE["h_low"]) * S
        zhi = (BASE["z_lo"] + BASE["h_high"]) * S - 1
        out[x, ylo:yhi + 1, zlo:zhi + 1] = True
    else:                                                       # pragma: no cover - frozen set
        raise ValueError("unknown perturbation kind %r" % (spec["kind"],))
    return out


def build_fixture(S: int, aperture=None, variant="mirror", swapped=False, perturbation=None):
    """The full virtual fixture at resolution S, with its frozen region and plane indices."""
    mask = scale(base_mask(aperture=aperture, variant=variant), S)
    if swapped:
        mask = swap_paths(mask)
    if perturbation is not None:
        mask = _apply_perturbation(mask, S, perturbation)
    return mask, fixture_meta(S, aperture=aperture, variant=variant, swapped=swapped,
                              perturbation=perturbation, mask=mask)


def fixture_meta(S, aperture=None, variant="mirror", swapped=False, perturbation=None, mask=None):
    """Every frozen index the observable calculation is allowed to use. Nothing here is fitted."""
    nx, ny, nz = BASE["nx"] * S, BASE["ny"] * S, BASE["nz"] * S
    lane1 = (BASE["lane1_lo"] * S, (BASE["lane1_hi"] + 1) * S)      # [lo, hi) voxel slices
    lane2 = (BASE["lane2_lo"] * S, (BASE["lane2_hi"] + 1) * S)
    if swapped:                       # the swap relabels nothing: lane 1 is still y-low
        pass
    meta = {
        "S": S, "variant": variant, "swapped": bool(swapped),
        "perturbation": perturbation, "aperture": None if aperture is None else dict(aperture),
        "shape": (nx, ny, nz),
        "lane1_y": lane1, "lane2_y": lane2,
        "divider_y": (BASE["div_lo"] * S, (BASE["div_hi"] + 1) * S),
        "lane_x": (BASE["lane_lo"] * S, (BASE["lane_hi"] + 1) * S),
        # ---- node surfaces: the plenum planes immediately abutting the lane ends. These are
        # the only planes where the cross-section is ONE connected common region, i.e. a genuine
        # network node (PROTOCOL §8.2).
        "x_node_in": BASE["lane_lo"] * S - 1,
        "x_node_out": (BASE["lane_hi"] + 1) * S,
        # frozen node-surface offsets for the §8.2 sensitivity report (further into the plenum)
        "node_offsets": (1, 2),
        # ---- outlet-flux measurement planes, both inside the downstream segment ----
        "x_meas_a": (BASE["lane_hi"] + 1) * S - 1,          # immediately before the plenum
        "x_meas_b": 48 * S,                                  # a second frozen plane, 5 base up
        "x_meas_in": BASE["lane_lo"] * S,                    # lane inlet plane (conservation)
        # ---- bridge instrumentation ----
        "y_bridge": (BASE["div_lo"] + 1) * S,                # mid-plane of the divider slab
        "y_face1": BASE["div_lo"] * S - 1,                   # last lane-1 voxel before the bridge
        "y_face2": (BASE["div_hi"] + 1) * S,                 # first lane-2 voxel after it
    }
    if aperture is not None:
        ax_lo, ax_hi = _base_aperture_x(int(aperture["kx"]))
        meta["aperture_x"] = (ax_lo * S, (ax_hi + 1) * S)
        meta["aperture_z"] = (BASE["z_lo"] * S, (BASE["z_lo"] + int(aperture["kz"])) * S)
    else:                       # blocked: the bridge footprint the SAME aperture would occupy
        meta["aperture_x"] = None
        meta["aperture_z"] = None
    if mask is not None:
        meta["mask_sha256"] = mask_hash(mask)
        meta["n_solid"] = int(mask.sum())
        meta["n_fluid"] = int((~mask).sum())
    return meta


def mask_hash(mask) -> str:
    """SHA-256 of the packed boolean mask plus its shape — the geometry's identity."""
    h = hashlib.sha256()
    h.update(("%d,%d,%d|" % mask.shape).encode())
    h.update(np.packbits(np.ascontiguousarray(mask, dtype=bool)).tobytes())
    return h.hexdigest()


def is_mirror_symmetric(mask, S: int) -> bool:
    """Exact voxel-index mirror test: swap_paths(mirror_x(mask)) == mask."""
    return bool(np.array_equal(swap_paths(mirror_x(mask, S)), mask))


def connectivity(mask, meta):
    """Connected-component audit of the fluid space: the required flow regions must form ONE
    component under x-periodic / y,z-walled connectivity, and no fluid may touch a y or z face."""
    from scipy import ndimage
    fluid = ~mask
    nx = mask.shape[0]
    # x-periodic labelling: label the doubled array then fold, so wrap-connections are seen.
    lab, n = ndimage.label(np.concatenate([fluid, fluid], axis=0))
    a, b = lab[:nx], lab[nx:]
    merge = {}
    for u, v in set(zip(a[fluid].ravel().tolist(), b[fluid].ravel().tolist())):
        merge.setdefault(u, set()).add(v)
    # union-find over the two copies
    parent = {}

    def find(k):
        parent.setdefault(k, k)
        while parent[k] != k:
            parent[k] = parent[parent[k]]
            k = parent[k]
        return k

    def union(p, q):
        rp, rq = find(p), find(q)
        if rp != rq:
            parent[rp] = rq

    for u, vs in merge.items():
        for v in vs:
            union(u, v)
    comps = {find(int(v)) for v in np.unique(a[fluid])}
    y_face = bool(fluid[:, 0, :].any() or fluid[:, -1, :].any())
    z_face = bool(fluid[:, :, 0].any() or fluid[:, :, -1].any())
    return {"n_components_raw": int(n), "n_components_periodic": len(comps),
            "fluid_on_y_face": y_face, "fluid_on_z_face": z_face,
            "single_connected": len(comps) == 1,
            "no_lateral_bypass": not (y_face or z_face)}


