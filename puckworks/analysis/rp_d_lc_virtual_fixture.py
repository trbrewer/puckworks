# 6. DECISION RULE  (PROTOCOL §12 — frozen before execution)
# ==========================================================================================

def _clause(name, ok, detail):
    return {"clause": name, "pass": bool(ok), "detail": detail}


def decide(runs):
    """Evaluate the frozen disposition rule against the joined records. Returns
    (disposition, clauses). ``runs`` is the compact record structure written by the slow driver
    and re-derived by ``assemble``."""
    cl = []
    ctrl = runs["controls"]

    # Execution validity. `frozen_C_linearity_control` is deliberately ABSENT from the required
    # set and present in the reported set: it is a preserved historical failure, and the question
    # it was meant to answer is now answered by `componentwise_creeping_flow_control` (can the
    # INTERNAL fields serve as truth?) and `boundary_inference_forcing_stability` (are the
    # BOUNDARY observables stable?). A stable R may never stand in for the componentwise test.
    REQUIRED = ("convergence", "low_mach_linearity", "componentwise_creeping_flow_control",
                "boundary_inference_forcing_stability", "mass_conservation", "topology",
                "coarse_graining_surface_stability", "plane_invariance", "grid_refinement")
    REPORTED = REQUIRED + ("frozen_C_linearity_control", "backend_cross_check")
    valid = all(ctrl[k]["pass"] for k in REQUIRED)
    # A control that FAILED ON EVIDENCE and one that was NOT EVALUATED are different things, and
    # the record must not conflate them: an unevaluated downstream control is a CONSEQUENCE of an
    # upstream failure, never itself the reason execution was judged invalid.
    def _st(k):
        return ctrl[k].get("status", "EVALUATED")

    failed_on_evidence = [k for k in REQUIRED
                          if not ctrl[k]["pass"] and _st(k) == "EVALUATED"]
    not_evaluated = [k for k in REQUIRED if _st(k) != "EVALUATED"]
    cl.append(_clause("1_execution_valid", valid,
                      {"required": {k: {"pass": ctrl[k]["pass"], "status": _st(k)}
                                    for k in REQUIRED},
                       "reported_not_required": {
                           k: {"pass": ctrl[k]["pass"], "status": _st(k)}
                           for k in REPORTED if k not in REQUIRED},
                       "failed_on_evidence": failed_on_evidence,
                       "not_evaluated_downstream": not_evaluated,
                       "primary_cause": failed_on_evidence[0] if failed_on_evidence else None,
                       "note": ("componentwise_creeping_flow_control is load-bearing: if the "
                                "internal components are not proportional to the forcing within "
                                "1e-4, a stable R cannot rescue the execution and the disposition "
                                "is INVALID_EXECUTION.")}))

    primary = [r for r in runs["cases"]
               if r["role"] == "primary" and r["S"] == max(SCIENTIFIC_RESOLUTIONS)]
    if not primary:
        primary = [r for r in runs["cases"] if r["role"] == "primary"]
    # Xi_field is None when the truth was unavailable (zero or sign-inconsistent bridge pressure
    # gap, e.g. the identical-path control). Such a case is NEVER silently treated as zero, and it
    # cannot enter the window set.
    def _usable(x):
        """None (rounded artifact) and NaN (raw record) both mean 'truth unavailable'."""
        return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)

    def _in_window(r):
        x = r["truth"].get("Xi_field")
        return _usable(x) and XI_WINDOW_LO <= x <= XI_WINDOW_HI

    window = [r for r in runs["cases"] if r["role"] == "primary" and _in_window(r)]
    unavailable = [{"S": r["S"], "aperture": r["aperture"]} for r in runs["cases"]
                   if r["role"] == "primary" and not _usable(r["truth"].get("Xi_field"))]
    per_res = {}
    for S in SCIENTIFIC_RESOLUTIONS:
        per_res[S] = [r for r in window if r["S"] == S]
    n_window_min = min((len(v) for v in per_res.values()), default=0)
    cl.append(_clause("2_three_window_cases", n_window_min >= 3,
                      {"per_resolution_counts": {str(k): len(v) for k, v in per_res.items()},
                       "window": [XI_WINDOW_LO, XI_WINDOW_HI],
                       "primary_cases_with_unavailable_Xi_field": unavailable}))

    ratios = [(r["S"], r["aperture"], r["inference"]["status"],
               (r["inference"]["Xi_hat"] / r["truth"]["Xi_field"])
               if r["inference"]["Xi_hat"] else None) for r in window]
    ok3 = bool(window) and all(
        st == "ok" and ra is not None and 0.5 <= ra <= 2.0 for _, _, st, ra in ratios)
    cl.append(_clause("3_factor_two_recovery", ok3, {"ratios": ratios}))

    cdiffs = [(r["S"], r["aperture"], r["inference"]["c_hat"], r["truth"]["c_field"])
              for r in window]
    ok4 = bool(window) and all(
        ch is not None and (ch > 0) == (cf > 0) and abs(ch - cf) <= 0.10
        for _, _, ch, cf in cdiffs)
    cl.append(_clause("4_contrast_sign_and_tolerance", ok4, {"pairs": cdiffs}))

    mono = {}
    for S in SCIENTIFIC_RESOLUTIONS:
        pts = sorted(((r["truth"]["Xi_field"], r["inference"]["Xi_hat"])
                      for r in runs["cases"] if r["role"] == "primary" and r["S"] == S
                      and _usable(r["inference"]["Xi_hat"])
                      and _usable(r["truth"].get("Xi_field"))), key=lambda t: t[0])
        mono[str(S)] = all(b[1] > a[1] for a, b in zip(pts, pts[1:])) if len(pts) > 1 else False
    cl.append(_clause("5_strict_monotonicity", all(mono.values()) and bool(mono), mono))

    swaps = runs["path_swap"]
    ok6 = bool(swaps) and all(s["signature_ok"] for s in swaps)
    cl.append(_clause("6_path_swap_signature", ok6,
                      [{"S": s["S"], "aperture": s["aperture"], **{k: s[k] for k in
                        ("share_sign_reversed", "c_sign_reversed", "R_preserved",
                         "Xi_field_preserved", "Xi_hat_preserved")}} for s in swaps]))

    cls_by_res = runs["grid_refinement"]["classification_by_resolution"]
    ok7 = len(set(cls_by_res.values())) == 1 and len(cls_by_res) >= 2
    cl.append(_clause("7_resolution_stable_classification", ok7, cls_by_res))

    passes = {c["clause"]: c["pass"] for c in cl}
    if not passes["1_execution_valid"]:
        return "INVALID_EXECUTION", cl
    if not passes["2_three_window_cases"]:
        return "DESIGN_MISSED_TARGET", cl
    if all(passes.values()):
        return "CROSS_MODEL_RECOVERY", cl
    mechanism = (passes["5_strict_monotonicity"] and passes["6_path_swap_signature"]
                 and runs["mechanism"]["bridge_flux_consistent"]
                 and runs["mechanism"]["R_direction_consistent"])
    return ("MECHANISM_ONLY" if mechanism else "NO_CROSS_MODEL_TRANSFER"), cl


