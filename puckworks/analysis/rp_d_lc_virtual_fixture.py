# 5. BOUNDARY-ONLY INFERENCE — the pipeline under test
# ==========================================================================================

#: The ONLY keys ``infer_from_boundary`` will accept. Anything else is a contract violation and
#: raises: no internal pressure, no bridge flux, no calibrated G_lat, no aperture size, no
#: c_truth, no Xi_truth, no fitted correction may reach the inverse (PROTOCOL §6).
BOUNDARY_KEYS = ("Q0", "dP0", "q1", "q2", "dP", "orientation", "converged")


def infer_from_boundary(record):
    """Blind boundary inversion. Accepts ONLY ``BOUNDARY_KEYS`` and delegates to the existing
    verified WP6 inverse — this module contains no inverse of its own.

        R = (Q/dP)_open / (Q0/dP0)_blocked        s = q1 / (q1 + q2)
    """
    keys = tuple(sorted(record))
    if keys != tuple(sorted(BOUNDARY_KEYS)):
        raise ValueError(
            "infer_from_boundary accepts exactly %r; got %r — the anti-circularity contract "
            "(PROTOCOL §6) forbids passing any truth-side quantity to the inverse."
            % (sorted(BOUNDARY_KEYS), list(keys)))
    q1, q2 = float(record["q1"]), float(record["q2"])
    Q = q1 + q2
    R = (Q / float(record["dP"])) / (float(record["Q0"]) / float(record["dP0"]))
    s = q1 / Q
    out = dict(wp6.invert(R, s))
    out["R"] = R
    out["s"] = s
    out["dP_ratio_open_over_blocked"] = float(record["dP"]) / float(record["dP0"])
    out["orientation"] = record["orientation"]
    out["converged"] = bool(record["converged"])
    return out


def network_prediction(g1_top, g1_bot, g2_top, g2_bot, G_lat):
    """Forward two-node network prediction of (R, s) from calibrated elements — used ONLY in
    Arm F, after inference is recorded, to separate inverse failure from reduction failure."""
    from puckworks.models import lateral_coupling as lc
    P = 1.0
    op = lc.model1_two_path(P, g1_top, g1_bot, g2_top, g2_bot, G_lat)
    bl = lc.model1_two_path(P, g1_top, g1_bot, g2_top, g2_bot, 0.0)
    return {"R": op["Q"] / bl["Q"], "s": op["q1"] / op["Q"]}


