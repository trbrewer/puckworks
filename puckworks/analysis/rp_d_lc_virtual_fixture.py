def build_axial_coupon(S: int, level: str, orientation: str = "x"):
    """A straight duct coupon reproducing one axial segment: same slot height, same lane width,
    same wall treatment (a 1-base-voxel outer wall on one side, the 2-base-voxel divider on the
    other), same length, x-periodic. ``orientation`` 'y' transposes the duct axis onto the y
    lattice direction and back, so the SAME duct is calibrated in two lattice orientations
    (PROTOCOL §11.6 anisotropy check) — the solver still drives +x."""
    if level not in ("high", "low"):
        raise ValueError("level must be 'high' or 'low', got %r" % (level,))
    if orientation not in ("x", "y"):
        raise ValueError("orientation must be 'x' or 'y', got %r" % (orientation,))
    h = BASE["h_high"] if level == "high" else BASE["h_low"]
    lx = BASE["seg_top_hi"] - BASE["seg_top_lo"] + 1               # 20 base voxels
    ny_b = BASE["div_hi"] + 1                                      # wall + lane 1 + divider
    solid_b = np.ones((lx, ny_b, BASE["nz"]), dtype=bool)
    solid_b[:, BASE["lane1_lo"]:BASE["lane1_hi"] + 1, BASE["z_lo"]:BASE["z_lo"] + h] = False
    mask = scale(solid_b, S)
    if orientation == "y":
        # Rotate the CROSS-SECTION, not the flow axis: the duct axis must stay along +x because
        # that is the only direction the kernel drives. Swapping axes 1 and 2 puts the slot's
        # narrow dimension along y instead of z, which is exactly the lattice-anisotropy test
        # (same duct, same length, same wall treatment, different lattice orientation).
        mask = np.ascontiguousarray(np.swapaxes(mask, 1, 2))
    meta = {"S": S, "kind": "axial_coupon", "level": level, "orientation": orientation,
            "length_vox": lx * S, "shape": tuple(int(v) for v in mask.shape),
            "mask_sha256": mask_hash(mask), "n_fluid": int((~mask).sum())}
    return mask, meta


#: Bridge-coupon plenum depth on each side of the divider, in base voxels, and the transverse
#: span it is embedded in. Frozen; NOT tuned against any assembled-fixture output.
BRIDGE_COUPON = {"plenum": 6, "span": 13}


def build_bridge_coupon(S: int, kx: int, kz: int):
    """AXIS-ROTATED bridge coupon: the divider slab and its aperture, rebuilt so the transverse
    (bridge) axis lies along the solver's +x lattice direction. The existing x-directed kernel
    therefore measures the transverse conductance directly, with no invented anisotropy
    correction. Plena of the transition-band slot height sit on both sides and join through the
    x wrap, exactly as the full fixture's common node does."""
    ax_lo, ax_hi = _base_aperture_x(int(kx))                       # validate against the family
    kz = int(kz)
    if not 1 <= kz <= BASE["h_low"]:
        raise ValueError("aperture kz must lie in 1..%d, got %r" % (BASE["h_low"], kz))
    p, span = BRIDGE_COUPON["plenum"], BRIDGE_COUPON["span"]
    w = BASE["div_hi"] - BASE["div_lo"] + 1                        # divider thickness = 2 base
    lx = 2 * p + w
    solid_b = np.ones((lx, span, BASE["nz"]), dtype=bool)
    # plena: the transition-band cross-section (slot height h_low), walled on both span faces
    solid_b[:p, 1:span - 1, BASE["z_lo"]:BASE["z_lo"] + BASE["h_low"]] = False
    solid_b[p + w:, 1:span - 1, BASE["z_lo"]:BASE["z_lo"] + BASE["h_low"]] = False
    # the aperture through the divider slab, centred on the span
    c = span // 2
    half = (int(kx) - 1) // 2
    solid_b[p:p + w, c - half:c + half + 1, BASE["z_lo"]:BASE["z_lo"] + kz] = False
    mask = scale(solid_b, S)
    meta = {"S": S, "kind": "bridge_coupon", "kx": int(kx), "kz": kz,
            "wall_thickness_vox": w * S, "plenum_vox": p * S,
            "shape": tuple(int(v) for v in mask.shape), "mask_sha256": mask_hash(mask),
            "n_fluid": int((~mask).sum()),
            "x_node_in": p * S - 1, "x_node_out": (p + w) * S,
            "aperture_x_extent_vox": int(kx) * S, "aperture_z_extent_vox": kz * S}
    return mask, meta


