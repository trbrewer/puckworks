def _code_value(module: str, attr: str, key):
    import importlib

    obj = getattr(importlib.import_module(module), attr)
    if key is None:
        return float(obj)
    for seg in (key if isinstance(key, tuple) else (key,)):
        obj = obj[seg]
    return float(obj)


def verify() -> dict:
    """Resolve every binding against its archive. Returns a report; never raises on a mismatch."""
    cache: dict[str, dict] = {}
    ok, mismatched, unresolvable = [], [], []
    for token, (module, attr, key, abs_) in sorted(CODE_CONSTANTS.items()):
        try:
            value = _code_value(module, attr, key)
        except Exception as exc:                                    # noqa: BLE001
            unresolvable.append((token, module, attr, f"{type(exc).__name__}: {exc}"))
            continue
        if abs(float(token) - value) <= float(abs_):
            ok.append((token, module, attr, value))
        else:
            mismatched.append((token, module, attr, value, float(token) - value))

    for token, (archive, fn, rel, abs_) in sorted(DERIVED.items()):
        try:
            if archive not in cache:
                cache[archive] = json.loads((ARCHIVE_DIR / archive).read_text(encoding="utf-8"))
            value = float(fn(cache[archive]))
        except Exception as exc:                                    # noqa: BLE001
            unresolvable.append((token, archive, "<derived>", f"{type(exc).__name__}: {exc}"))
            continue
        claimed = float(token)
        if abs(claimed - value) <= max(float(abs_), float(rel) * abs(value)):
            ok.append((token, archive, "<derived>", value))
        else:
            mismatched.append((token, archive, "<derived>", value, claimed - value))

    for token, (archive, path, transform, rel, abs_) in sorted(BINDINGS.items()):
        try:
            if archive not in cache:
                cache[archive] = json.loads(
                    (ARCHIVE_DIR / archive).read_text(encoding="utf-8"))
            value = _resolve(cache[archive], path)
            if transform is not None:
                value = transform(value)
            value = float(value)
        except Exception as exc:                                    # noqa: BLE001
            unresolvable.append((token, archive, path, f"{type(exc).__name__}: {exc}"))
            continue
        claimed = float(token)
        tol = max(float(abs_), float(rel) * abs(value))
        if abs(claimed - value) <= tol:
            ok.append((token, archive, path, value))
        else:
            mismatched.append((token, archive, path, value, claimed - value))
    return dict(n_bound=len(BINDINGS) + len(DERIVED) + len(CODE_CONSTANTS), n_ok=len(ok), n_mismatched=len(mismatched),
                n_unresolvable=len(unresolvable), n_declared_unbindable=len(UNBINDABLE),
                ok=ok, mismatched=mismatched, unresolvable=unresolvable)


def main(argv=None) -> int:                                          # pragma: no cover
    import sys
    argv = sys.argv[1:] if argv is None else list(argv)
    r = verify()
    if "--json" in argv:
        print(json.dumps({k: v for k, v in r.items() if not isinstance(v, list)}, indent=2))
        return 1 if (r["n_mismatched"] or r["n_unresolvable"]) else 0
    print(f"slow-lane bindings: {r['n_ok']}/{r['n_bound']} resolve and match; "
          f"{r['n_mismatched']} mismatched; {r['n_unresolvable']} unresolvable; "
          f"{r['n_declared_unbindable']} declared unbindable")
    for token, archive, path, value, delta in r["mismatched"]:
        print(f"  MISMATCH {token:>10}  {archive}:{path}  archived {value!r}  delta {delta:+.6g}")
    for token, archive, path, why in r["unresolvable"]:
        print(f"  UNRESOLVABLE {token:>10}  {archive}:{path}  {why}")
    return 1 if (r["n_mismatched"] or r["n_unresolvable"]) else 0


