"""Bind Paper 1's SLOW-LANE manuscript numbers to the archived records that produced them.

`claim_coverage.SLOW_LANE_RESULTS` records, for each slow-lane number in the manuscript, a prose
sentence naming the producer and the archive. That is documentation, not verification: nothing
opens the archive and checks that the manuscript's number is still the archived one. Six review
rounds found stale numbers by hand in exactly this population.

This module closes that gap without rerunning anything. Each binding names a **path into a
committed archive**, and `verify()` resolves it and compares. Rerunning the slow lane is not
required — the archives were written by the runs that produced the manuscript's numbers, so
comparing against them catches the failure mode that actually occurs (the analysis is rerun and the
prose is not updated, or the prose is edited and the analysis is not).

    python -m puckworks.paper_a.slow_lane_bindings          # report
    python -m puckworks.paper_a.slow_lane_bindings --json   # machine-readable

A binding is a `(archive, path, transform)` triple:

* ``archive``  — file under `docs/paper1_resource/`.
* ``path``     — dotted path into the JSON; list indices are numeric segments.
* ``transform``— optional callable applied to the archived value before comparison, for the cases
  where the manuscript legitimately quotes a rounded, signed, or percentage-scaled form.

`rel` / `abs` tolerances exist because the manuscript quotes numbers at display precision. The
tolerance is deliberately tight enough that a genuine drift fails: a value quoted to 2 dp is
checked to 2 dp, not to "close enough".
"""
